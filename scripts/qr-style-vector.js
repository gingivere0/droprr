// Writes tests/Droprr.Windows.Tests/qr-style-vector.txt from site/qrstyle.js, the reference implementation of the
// styled QR code, so the Windows port is tested against it. Run from the repository root: node scripts/qr-style-vector.js
global.self = global;
global.qrcode = require("../site/vendor/qrcode.js");
require("../site/qrstyle.js");
const text = "https://gingivere0.github.io/droprr/#AAAAAAAAAAAAAAAAAAAAAA.BBBBBBBBBBBBBBBBBBBBBB.CCCCCCCCCCCCCCCCCCCCCC.AgEDESIzRFVmd4iZqrvM3e7_ZEAMIsCoAR4";
const qr = qrcode(0, "Q");
qr.addData(text);
qr.make();
const n = qr.getModuleCount();
const kinds = DroprrQR.classify((r, c) => qr.isDark(r, c), n);
const matrix = [], expected = [];
for (let r = 0; r < n; r++) {
  let row = "", kind = "";
  for (let c = 0; c < n; c++) { row += qr.isDark(r, c) ? "1" : "0"; kind += kinds[r * n + c]; }
  matrix.push(row);
  expected.push(kind);
}
require("fs").writeFileSync(require("path").join(__dirname, "../tests/Droprr.Windows.Tests/qr-style-vector.txt"),
  "# Generated by scripts/qr-style-vector.js from site/qrstyle.js: the code matrix (1 = dark), a blank line, then the\n" +
  "# expected classification (0 light, 1 outer, 2 inner, 3 eye).\n" + matrix.join("\n") + "\n\n" + expected.join("\n") + "\n");
